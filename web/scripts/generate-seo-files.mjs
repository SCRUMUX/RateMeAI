#!/usr/bin/env node
/**
 * Variant B prebuild step — generates `public/sitemap.xml` and
 * `public/robots.txt` from a shared route catalogue, customised for
 * the active market and origin.
 *
 * Inputs (env):
 *   * VITE_MARKET_ID  — `ru` (default) or `global`.
 *   * VITE_WEB_ORIGIN — public origin of THIS build. Falls back to the
 *     canonical origin for the active market.
 *
 * Output: overwrites public/sitemap.xml and public/robots.txt with
 * the absolute URLs that match the build's target domain.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PUBLIC_DIR = resolve(__dirname, '..', 'public');

const MARKET = (process.env.VITE_MARKET_ID ?? 'global').toLowerCase().trim() || 'global';

const CANONICAL_BY_MARKET = {
  ru: 'https://ailookstudio.ru',
  global: 'https://ailookstudio.vercel.app',
};

const PRIMARY_ORIGIN = (process.env.VITE_WEB_ORIGIN ?? '').trim().replace(/\/$/, '')
  || CANONICAL_BY_MARKET[MARKET]
  || CANONICAL_BY_MARKET.global;

// Companion origin for hreflang. RU build advertises the global SPA
// as the alternate (and vice versa) so Google can pair the two.
const ALTERNATE_ORIGIN = MARKET === 'ru'
  ? CANONICAL_BY_MARKET.global
  : CANONICAL_BY_MARKET.ru;

const ALTERNATE_HREFLANG = MARKET === 'ru' ? 'en' : 'ru';

const ROUTES = [
  { path: '/', priority: '1.0', changefreq: 'weekly' },
  { path: '/dokumenty', priority: '0.9', changefreq: 'weekly' },
  { path: '/znakomstva', priority: '0.9', changefreq: 'weekly' },
  { path: '/rezume', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/schengen', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/usa', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/uk', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/canada', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/japan', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/china', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/uae', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/australia', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/korea', priority: '0.9', changefreq: 'weekly' },
  { path: '/visa/india', priority: '0.9', changefreq: 'weekly' },
  { path: '/privacy', priority: '0.3', changefreq: 'monthly' },
];

function urlEntry(path, priority, changefreq) {
  const ru = `${CANONICAL_BY_MARKET.ru}${path}`;
  const global = `${CANONICAL_BY_MARKET.global}${path}`;
  const primary = `${PRIMARY_ORIGIN}${path}`;
  return [
    '  <url>',
    `    <loc>${primary}</loc>`,
    `    <xhtml:link rel="alternate" hreflang="ru" href="${ru}" />`,
    `    <xhtml:link rel="alternate" hreflang="en" href="${global}" />`,
    `    <xhtml:link rel="alternate" hreflang="x-default" href="${global}" />`,
    `    <changefreq>${changefreq}</changefreq>`,
    `    <priority>${priority}</priority>`,
    '  </url>',
  ].join('\n');
}

const sitemapBody = ROUTES.map(({ path, priority, changefreq }) => urlEntry(path, priority, changefreq)).join('\n');

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${sitemapBody}
</urlset>
`;

const robots = `# Generated by web/scripts/generate-seo-files.mjs for VITE_MARKET_ID=${MARKET}
User-agent: *
Allow: /
Disallow: /admin/
Disallow: /auth/callback
Disallow: /payment-success

Sitemap: ${PRIMARY_ORIGIN}/sitemap.xml
`;

mkdirSync(PUBLIC_DIR, { recursive: true });
writeFileSync(join(PUBLIC_DIR, 'sitemap.xml'), sitemap, 'utf-8');
writeFileSync(join(PUBLIC_DIR, 'robots.txt'), robots, 'utf-8');

// eslint-disable-next-line no-console
console.log(
  `[seo] wrote sitemap.xml + robots.txt for market=${MARKET} origin=${PRIMARY_ORIGIN} alt=${ALTERNATE_ORIGIN}/${ALTERNATE_HREFLANG}`,
);
